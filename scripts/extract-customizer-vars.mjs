/**
 * Generates src/customizer/registry.generated.ts from the installed Blades CSS
 * (node_modules/@anyblades/blades/css/layered/variables{,-blades}.css) and the
 * repo's own Knives role CSS (src/assets/roles/knives.css).
 *
 * Run with `pnpm extract-vars`; regenerate whenever the Blades version changes.
 * Output is committed and prettier-ignored (.prettierignore).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const bladesDir = join(require.resolve('@anyblades/blades/css/layered/variables.css'), '..');
const root = new URL('..', import.meta.url).pathname;

/** var name → { source, value, selector } — first sighting wins. */
const out = new Map();

/** Parse "selector { body }" blocks, tracking each rule's selector correctly. */
function* blocks(css) {
	let depth = 0;
	let braceStart = -1;
	let prev = 0;
	for (let i = 0; i < css.length; i++) {
		const ch = css[i];
		if (ch === '{') {
			if (depth === 0) braceStart = i;
			depth++;
		} else if (ch === '}') {
			depth--;
			if (depth === 0) {
				yield { selector: css.slice(prev, braceStart).trim(), body: css.slice(braceStart + 1, i) };
				prev = i + 1;
			}
		}
	}
}

const compact = (s) => s.replace(/\s+/g, ' ').trim();

function collect(source, css, skipMedia = false) {
	// Drop comments, `@media` overrides (they repeat base declarations) and a
	// possible single `@layer` wrapper so the block parser sees plain rules.
	let clean = css
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.replace(/@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, '');
	const layer = clean.match(/^\s*@\w+[^{]*\{/);
	if (layer) clean = clean.slice(layer[0].length).replace(/\}\s*$/, '');
	for (const { selector, body } of blocks(clean)) {
		if (!body.includes('--')) continue;
		if (skipMedia && selector === '') continue;
		for (const m of body.matchAll(/(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);/g)) {
			const name = m[1];
			if (name.startsWith('--in-')) continue;
			if (out.has(name)) continue;
			const rootScoped = /:scope|:host/.test(selector) || selector === ':root';
			out.set(name, {
				source,
				value: compact(m[2]),
				selector: rootScoped ? null : compact(selector),
			});
		}
	}
}

collect('pico', readFileSync(join(bladesDir, 'variables.css'), 'utf8'));
collect('blades', readFileSync(join(bladesDir, 'variables-blades.css'), 'utf8'));
const knivesPath = join(root, 'src/assets/roles/knives.css');
collect('knives', readFileSync(knivesPath, 'utf8'), true);

// input[type=color] requires 6-digit hex; expand 3-digit initials.
function normalizeHex(value) {
	return value.replace(
		/^#([0-9a-f])([0-9a-f])([0-9a-f])\b/i,
		(_m, r, g, b) => `#${r}${r}${g}${g}${b}${b}`,
	);
}

const TYPES = (value) => {
	if (value === null) return 'text';
	if (/url\(/.test(value)) return 'url';
	if (/(^|\s)(#[0-9a-f]{3,8}|light-dark|rgb|hsl|oklch)/i.test(value)) return 'color';
	if (/rem|em|px|%|\b0\.\d+\b/.test(value)) return 'length';
	return 'text';
};

const CATEGORY = (name, source) => {
	if (source === 'blades') return 'Tokens';
	if (source === 'knives') return 'Knives';
	const p = name.replaceAll('--pico-', '');
	if (/^icon/.test(p)) return 'Icons';
	if (/^form-element|^nav-element|^nav-link/.test(p)) return 'Forms & navigation';
	if (/^table|^code/.test(p)) return 'Code & tables';
	if (/-shadow|box-shadow/.test(p)) return 'Shadows';
	if (/^h[1-6]/.test(p) || /typography|font-|line-height|text-selection/.test(p))
		return 'Typography';
	if (/spacing|gap|border-radius|border-width|outline/.test(p)) return 'Spacing & sizing';
	if (/color|background|underline|focus|inverse|mark|ins|del|blockquote/.test(p)) return 'Colors';
	return 'Misc';
};

const defs = [...out.entries()]
	.map(([name, { source, value, selector }]) => ({
		id: `${source}.${name.replace(/^--([a-z]+)-/, '$1.')}`,
		name,
		source,
		category: CATEGORY(name, source),
		type: TYPES(value),
		initial: normalizeHex(value),
		// The heading rule in the source spans h1–h6; emit the full selector
		// set so the applier targets every heading.
		...(selector ? { selector: selector === 'h1' ? 'h1, h2, h3, h4, h5, h6' : selector } : {}),
	}))
	.sort((a, b) => a.source.localeCompare(b.source) || a.name.localeCompare(b.name));

const bladesRoot = join(bladesDir, '..', '..'); // css/layered → package dir
const pkg = JSON.parse(readFileSync(join(bladesRoot, 'package.json'), 'utf8'));
const banner = `// GENERATED by scripts/extract-customizer-vars.mjs — do not edit by hand.
// Regenerate with \`pnpm extract-vars\` after a Blades upgrade
// (currently @anyblades/blades@${pkg.version}).
`;

const body = `export interface GeneratedDef {
	id: string;
	/** Full custom property name, keys of the theme value maps. */
	name: string;
	source: 'pico' | 'blades' | 'knives';
	category: string;
	type: 'color' | 'length' | 'text' | 'url';
	initial: string;
	/** Selector the variable is declared on when not root-scoped. */
	selector?: string;
}

export const generatedVersion = ${JSON.stringify(pkg.version)};
export const generatedDefinitions: GeneratedDef[] = ${JSON.stringify(defs, null, 2)};
`;

const content = banner + body;
const outPath = join(root, 'src/customizer/registry.generated.ts');

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(outPath, 'utf8');
	} catch {}
	if (current !== content) {
		console.error(
			`registry.generated.ts is stale (${defs.length} defs generated). Run \`pnpm extract-vars\` and commit the result.`,
		);
		process.exit(1);
	}
	console.log(
		`registry.generated.ts is current (${defs.length} definitions, blades@${pkg.version}).`,
	);
	process.exit(0);
}

writeFileSync(outPath, content);
console.log(`registry.generated.ts: ${defs.length} definitions written.`);
